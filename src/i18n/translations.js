export function localizeCategoryName(category, lang) {
  const locale = normalizeLanguage(lang);
  return categoryNames[category?.slug]?.[locale] || category?.name?.[locale] || category?.name?.en || category?.name || "";
}

export function localizeCategoryDescription(category, lang) {
  const locale = normalizeLanguage(lang);
  return categoryDescriptions[category?.slug]?.[locale] || category?.blurb || "";
}

export function localizeCategoryGroup(group, lang) {
  const locale = normalizeLanguage(lang);
  return categoryGroups[group]?.[locale] || group;
}

export function localizeOffer(offer, lang) {
  const locale = normalizeLanguage(lang);
  const copy = offerCopy[offer?.id]?.[locale];
  return copy ? { ...offer, title: copy[0], note: copy[1] } : offer;
}

export function localizeCoupon(coupon, lang) {
  const key = coupon?.firstOrderOnly ? "coupon_first_order_discount" : "coupon_cart_discount";
  return { ...coupon, label: t(lang, key) };
}

export function localizeAddressLabel(label, lang) {
  const locale = normalizeLanguage(lang);
  const key = `common_${String(label).toLowerCase()}`;
  return translations[locale][key] || label;
}

export function localizeTier(tier, lang) {
  const locale = normalizeLanguage(lang);
  const key = `loyalty_${String(tier).toLowerCase()}`;
  return translations[locale][key] || tier;
}
