export function normalizeLanguage(lang) {
  return languageOptions.some(({ code }) => code === lang) ? lang : "en";
}

export function t(lang, key, values = {}) {
  const locale = normalizeLanguage(lang);
  const message = translations[locale][key] ?? translations.en[key] ?? key;
  if (typeof message !== "string" || !values || typeof values !== "object") return message;
  const numberLocale = languageOptions.find(({ code }) => code === locale)?.locale || "en-IN";
  return message.replace(/\{(\w+)\}/g, (placeholder, name) => (
    Object.hasOwn(values, name)
      ? typeof values[name] === "number" ? new Intl.NumberFormat(numberLocale).format(values[name]) : String(values[name])
      : placeholder
  ));
}

